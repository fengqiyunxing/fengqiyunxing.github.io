//#region src/utils/url-utils.ts
function removeFileExtension(id) {
	return id.replace(/\.(md|mdx|markdown)$/i, "");
}
function joinUrl(...parts) {
	if (parts[0]?.startsWith("http://") || parts[0]?.startsWith("https://") || parts[0]?.startsWith("//")) return parts.join("").replace(/(?<!:)\/+/g, "/");
	return parts.join("/").replace(/\/+/g, "/");
}
function getPostUrlBySlug(slug) {
	return url(`/posts/${removeFileExtension(slug)}/`);
}
function getTagUrl(tag) {
	if (!tag) return url("/archive/");
	return url(`/archive/?tag=${encodeURIComponent(tag.trim())}`);
}
function getCategoryUrl(category) {
	if (!category || category.trim() === "" || category.trim().toLowerCase() === i18n(I18nKey.uncategorized).toLowerCase()) return url("/archive/?uncategorized=true");
	return url(`/archive/?category=${encodeURIComponent(category.trim())}`);
}
function getFileDirFromPath(filePath) {
	return filePath.replace(/^src\//, "").replace(/\/[^/]+$/, "");
}
function getSearchUrl(query) {
	return url(`/search/?q=${encodeURIComponent(query.trim())}`);
}
function url(path) {
	if (path.startsWith("http://") || path.startsWith("https://") || path.startsWith("//")) return path;
	return joinUrl("", "/", path);
}
